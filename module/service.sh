warp_down
phone_dns_rules_off
rm -f "$DNSPROXY_PID_FILE" /data/local/tmp/vpn_tether_probe.*
dnsproxy_port_guard_down
dnsproxy_exempt_down       # исключение AdGuard от убитого демона

