cleanup_all_rules
clear_rules_file
quic_block_down            # хвосты от убитого демона
zapret_rules_off
zapret_kill_all
opera_leftovers_cleanup    # обновились с 3.13–3.15.1 без перезагрузки
quic_block_apply
