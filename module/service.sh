[ -f /data/misc/net/rt_tables ] && log "rt_tables found" || log "WARNING: rt_tables not found, continuing anyway"

TUN_NAME=$(detect_tun_name)
log "TUN: $TUN_NAME"

dnsproxy_kill_strays
