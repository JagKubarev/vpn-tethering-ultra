zapret_strategy_valid() {
    case "$1" in fakeddisorder|md5sig|md5sig2|badseq|disorder|seqovl|custom) return 0 ;; esac
    return 1
}
# Только --dpi-desync*; @ — лишь встроенные подделки (=@G / =@Q), никаких
# путей: строка уходит в nfqws, запущенный от root. И для vpn_tether.conf,
# и для стратегий сетей (файл пишут WebUI и подбор).
zapret_args_valid() {
    local _t
    case "$1" in *[!A-Za-z0-9,.:+_@=\ -]*) return 1 ;; esac
    for _t in $1; do
        # 3.6: и --dup*, --orig-*, --wssize* (новые приёмы подбора)
        case "$_t" in --dpi-desync|--dpi-desync=*|--dpi-desync-*|--dup=*|--dup-*|--orig-*|--wssize=*|--wssize-*) ;; *) return 1 ;; esac
        case "$_t" in *@*) case "$_t" in *=@G|*=@Q) ;; *) return 1 ;; esac ;; esac
    done
    return 0
}
_ip4_valid() {
    local IFS=. o n=0
    case "$1" in ''|*[!0-9.]*|*..*|.*|*.) return 1 ;; esac
    for o in $1; do
        n=$((n + 1))
        [ "$o" -le 255 ] 2>/dev/null || return 1
    done
    [ "$n" = 4 ]
}

_conf_set() {   # _conf_set KEY VALUE  (KEY уже из белого списка)
    local key="$1" val="$2" ok=1
    case "$key" in
        DNSPROXY_ENABLE|DNS_PHONE|KILL_SWITCH|KILL_SWITCH_STRICT|NET_PROFILE_ADAPTIVE|STATUS_IN_DESCRIPTION|\
        ZAPRET_ENABLE|ZAPRET_PHONE|ZAPRET_QUIC_BLOCK|ZAPRET_QUIC_FAKE|QUIC_BLOCK_YT|QUIC_YT_FAKE|ZAPRET_PER_NET|DNS_META_EU|YT_GGC_BLOCK|\
        YT_DEAD_FAILFAST|ZAPRET_WATCHDOG|TETHER_STEALTH|TETHER_TTL_STRICT|ZAPRET_ALT|YT_SLOW_RETRY|WARP_ENABLE|WARP_GOOGLE|WARP_TELEGRAM|WARP_PHONE)
            case "$val" in 0|1) ;; *) ok=0 ;; esac ;;
        ZAPRET_WATCHDOG_MIN)
            case "$val" in ''|*[!0-9]*) ok=0 ;; *) [ "$val" -ge 5 ] && [ "$val" -le 240 ] || ok=0 ;; esac ;;
        ZAPRET_ALT_MIN)
            case "$val" in ''|*[!0-9]*) ok=0 ;; *) [ "$val" -ge 30 ] && [ "$val" -le 1440 ] || ok=0 ;; esac ;;
        ZAPRET_AUTO_FAIL)
            case "$val" in ''|*[!0-9]*) ok=0 ;; *) [ "$val" -ge 2 ] && [ "$val" -le 10 ] || ok=0 ;; esac ;;
        ZAPRET_MODE)     case "$val" in list|all) ;; *) ok=0 ;; esac ;;
        WARP_CONF)       # имя конфига, как в warp/warp.sh; пусто — по порядку
            case "$val" in *[!A-Za-z0-9_.-]*|.*) ok=0 ;; esac
            [ ${#val} -le 40 ] || ok=0 ;;
        ZAPRET_STRATEGY) zapret_strategy_valid "$val" || ok=0 ;;
        ZAPRET_ARGS)     zapret_args_valid "$val" || ok=0 ;;
        DNS_META_ECS)    _ip4_valid "$val" || ok=0 ;;
        DNS_DIRECT) case "$val" in doh|plain) ;; *) ok=0 ;; esac ;;
        DNS_VPN)    case "$val" in dnat|cache|doh) ;; *) ok=0 ;; esac ;;
        DNS_HEALTH_INTERVAL|DNS_HEALTH_RECOVER)
            case "$val" in ''|*[!0-9]*) ok=0 ;; *) [ "$val" -ge 2 ] && [ "$val" -le 600 ] || ok=0 ;; esac ;;
        DNS_UPSTREAMS|DNS_FALLBACKS|DNS_VPN_UPSTREAMS|DNS_BOOTSTRAP|DNS_META_UPSTREAMS)
            # только адреса апстримов: буквы, цифры, : / . - _ [ ] и пробелы
            case "$val" in ''|*[!A-Za-z0-9:/._\ \[\]-]*) ok=0 ;; esac
            # и не флаг dnsproxy (токен с «-»: «-o /data/…»)
            case " $val" in *" -"*) ok=0 ;; esac
            # bootstrap — только ip:порт: имя в -b dnsproxy не примет и не стартует
            # (tls://1.1.1.1 с IP он принял бы, но ip:порт — проще и хватает)
            [ "$key" = "DNS_BOOTSTRAP" ] && case "$val" in *[!0-9a-fA-F.:\ \[\]]*) ok=0 ;; esac ;;
        WARP_DOMAINS)
            # домены через пробел; пусто — выключить
            case "$val" in *[!a-z0-9.\ -]*) ok=0 ;; esac
            [ ${#val} -le 2000 ] || ok=0 ;;
        QUIC_BLOCK_APPS|WARP_APPS)
            # имена пакетов; пусто — допустимо (выключить)
            case "$val" in *[!A-Za-z0-9._\ ]*) ok=0 ;; esac ;;
        *) ok=0 ;;
    esac
    if [ "$ok" = "1" ]; then
        eval "$key=\"\$val\""
        USER_CONF_NOTE="$USER_CONF_NOTE $key"
    else
        USER_CONF_NOTE="$USER_CONF_NOTE !$key(неверное значение)"
    fi
}
load_user_conf() {
    local line key val
    [ -f "$USER_CONF" ] || return 0
    while IFS= read -r line || [ -n "$line" ]; do
        line=$(printf '%s' "$line" | tr -d '\r')
        line="${line%%#*}"
        case "$line" in *=*) ;; *) continue ;; esac
        key=$(printf '%s' "${line%%=*}" | tr -d ' \t')
        val=$(printf '%s' "${line#*=}" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')
        val="${val#\"}"; val="${val%\"}"; val="${val#\'}"; val="${val%\'}"
        [ -n "$key" ] || continue
        case " $CONF_KEYS " in
            *" $key "*) _conf_set "$key" "$val" ;;
            *) USER_CONF_NOTE="$USER_CONF_NOTE ?$key(неизвестный ключ)" ;;
        esac
    done < "$USER_CONF"
}

